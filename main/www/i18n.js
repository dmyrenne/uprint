function pickLang() {
  try { const l = localStorage.getItem('uprint-lang'); if (l in I18N) return l; } catch {}
  for (const l of navigator.languages || [navigator.language]) {
    const base = String(l).slice(0, 2).toLowerCase();
    if (base in I18N) return base;
  }
  return 'en';
}
let LANG = pickLang();

function t(key, vars = {}) {
  const s = I18N[LANG][key] ?? I18N.de[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? vars[k] : m));
}

// Statische Texte: data-i18n (Text), data-i18n-html, data-i18n-placeholder, data-i18n-aria
function applyI18n(root = document) {
  document.documentElement.lang = LANG;
  for (const el of root.querySelectorAll('[data-i18n]')) el.textContent = t(el.dataset.i18n);
  for (const el of root.querySelectorAll('[data-i18n-html]')) el.innerHTML = t(el.dataset.i18nHtml);
  for (const el of root.querySelectorAll('[data-i18n-placeholder]')) el.placeholder = t(el.dataset.i18nPlaceholder);
  for (const el of root.querySelectorAll('[data-i18n-aria]')) el.setAttribute('aria-label', t(el.dataset.i18nAria));
}
